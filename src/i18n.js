export function setLang(lang, page = "home") {
  const dict = I18N[lang];
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (dict[key] !== undefined) {
      node.textContent = dict[key];
    }
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((node) => {
    const key = node.getAttribute("data-i18n-ph");
    if (dict[key] !== undefined) {
      node.setAttribute("placeholder", dict[key]);
    }
  });
  document.documentElement.lang = lang;
  document.getElementById("langRu").className = lang === "ru" ? "on" : "";
  document.getElementById("langEn").className = lang === "en" ? "on" : "";
  document.title = TITLES[page][lang];
}

export function initLang(page = "home") {
  document.getElementById("langRu").addEventListener("click", () => {
    setLang("ru", page);
  });
  document.getElementById("langEn").addEventListener("click", () => {
    setLang("en", page);
  });
}
